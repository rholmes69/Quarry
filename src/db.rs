#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splits_respecting_strings_and_triggers() {
        let script = "CREATE TABLE t(a); INSERT INTO t VALUES('x;y');\n\
                      CREATE TRIGGER tr AFTER INSERT ON t BEGIN INSERT INTO t VALUES(1); END;\n\
                      -- trailing comment ;\nSELECT * FROM t";
        let s = split_statements(script);
        assert_eq!(s.len(), 4, "{s:#?}");
        assert!(s[1].contains("'x;y'"));
        assert!(s[2].ends_with("END;"));
        assert!(s[3].ends_with("SELECT * FROM t"));
    }

    #[test]
    fn classifies_transaction_sensitive_statements() {
        assert_eq!(classify("vacuum"), StmtClass::NeedsNoTransaction);
        assert_eq!(classify("PRAGMA journal_mode = WAL;"), StmtClass::NeedsNoTransaction);
        assert_eq!(classify("PRAGMA journal_mode;"), StmtClass::Normal);
        assert_eq!(classify("BEGIN IMMEDIATE"), StmtClass::TransactionControl);
        assert_eq!(classify("ROLLBACK TO sp"), StmtClass::Normal);
        assert_eq!(classify("/* hi */ COMMIT"), StmtClass::TransactionControl);
    }

    #[test]
    fn logs_app_and_user_statements_and_reverts() {
        let mut db = Database::open_in_memory().unwrap();
        let out = db.execute_script("CREATE TABLE t(a INTEGER, b TEXT); INSERT INTO t VALUES (1,'one');", 100);
        assert!(out.iter().all(|o| o.ok), "{out:?}");
        assert!(db.has_pending_changes());
        db.revert_changes().unwrap();
        assert!(db.table_names(false).unwrap().is_empty());

        db.execute_script("CREATE TABLE t(a INTEGER, b TEXT);", 100);
        db.write_changes().unwrap();
        db.execute_edit("INSERT INTO t VALUES (?1, ?2);", &[Value::Integer(7), Value::Text("it's".into())])
            .unwrap();
        db.write_changes().unwrap();
        // Expanded SQL with the bound parameters appears in the log.
        assert!(db.log.iter().any(|l| l.source == LogSource::App && l.sql.contains("VALUES (7, 'it''s')")));
        assert!(db.log.iter().any(|l| l.source == LogSource::User && l.sql.starts_with("CREATE TABLE")));
        assert!(db.log.iter().any(|l| l.sql.contains("SAVEPOINT \"RESTOREPOINT\"")));
    }

    #[test]
    fn vacuum_blocked_while_pending() {
        let mut db = Database::open_in_memory().unwrap();
        db.execute_script("CREATE TABLE t(a);", 10);
        let out = db.execute_script("VACUUM;", 10);
        assert!(!out[0].ok);
        db.write_changes().unwrap();
        let out = db.execute_script("VACUUM;", 10);
        assert!(out[0].ok, "{out:?}");
    }

    #[test]
    fn details_detect_strict_and_without_rowid() {
        let mut db = Database::open_in_memory().unwrap();
        db.execute_script(
            "CREATE TABLE s(id INTEGER PRIMARY KEY, v TEXT) STRICT;\
             CREATE TABLE w(k TEXT PRIMARY KEY, v) WITHOUT ROWID;\
             CREATE INDEX s_v ON s(v);",
            10,
        );
        let s = db.table_details("s").unwrap();
        assert!(s.strict && !s.without_rowid);
        assert_eq!(s.indexes.len(), 1);
        assert_eq!(s.indexes[0].columns, vec!["v"]);
        let w = db.table_details("w").unwrap();
        assert!(w.without_rowid);
        assert_eq!(w.pk_columns(), vec!["k"]);
    }

    #[test]
    fn wal_mode_and_checkpoint() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("w.db");
        let mut db = Database::open(&path, false).unwrap();
        let mode = db.set_pragma("journal_mode", "WAL").unwrap();
        assert_eq!(as_text(&mode).to_lowercase(), "wal");
        db.execute(LogSource::App, "CREATE TABLE t(a);", &[]).unwrap();
        db.execute(LogSource::App, "INSERT INTO t VALUES (1);", &[]).unwrap();
        assert!(db.wal_files()[0].1.unwrap_or(0) > 0);
        let (busy, _log, _ck) = db.wal_checkpoint("TRUNCATE").unwrap();
        assert_eq!(busy, 0);
        assert_eq!(db.wal_files()[0].1, Some(0));
    }
}
