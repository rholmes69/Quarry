//! Database layer.
//!
//! Every statement that touches SQLite goes through [`Database`] so it can be
//! recorded in the SQL log, tagged with who submitted it: the application
//! (statements generated behind visual UI actions) or the user (statements
//! typed into the Execute SQL tab). This mirrors DB4S's "SQL Log" pane.
//!
//! Edits made from the UI are wrapped in a savepoint (`RESTOREPOINT`) so they
//! can be written or reverted as a batch, again like DB4S.

use std::path::{Path, PathBuf};
use std::time::Instant;

use rusqlite::types::Value;
use rusqlite::{Connection, OpenFlags};

pub type Result<T> = std::result::Result<T, String>;

const SAVEPOINT: &str = "RESTOREPOINT";

// ---------------------------------------------------------------------------
// SQL log
// ---------------------------------------------------------------------------

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LogSource {
    /// Generated by the application behind a UI action.
    App,
    /// Typed by the user in the Execute SQL tab.
    User,
}

#[derive(Clone, Debug)]
pub struct LogEntry {
    pub time: String,
    pub source: LogSource,
    pub sql: String,
    pub ok: bool,
    pub millis: f64,
    /// Rows affected / returned, or the error message.
    pub detail: String,
}

// ---------------------------------------------------------------------------
// Schema model
// ---------------------------------------------------------------------------

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ObjKind {
    Table,
    View,
    Index,
    Trigger,
}

impl ObjKind {
    pub fn label(self) -> &'static str {
        match self {
            ObjKind::Table => "Tables",
            ObjKind::View => "Views",
            ObjKind::Index => "Indices",
            ObjKind::Trigger => "Triggers",
        }
    }
    pub fn sql_word(self) -> &'static str {
        match self {
            ObjKind::Table => "TABLE",
            ObjKind::View => "VIEW",
            ObjKind::Index => "INDEX",
            ObjKind::Trigger => "TRIGGER",
        }
    }
}

#[derive(Clone, Debug)]
pub struct SchemaObject {
    pub kind: ObjKind,
    pub name: String,
    pub tbl_name: String,
    pub sql: Option<String>,
}

#[derive(Clone, Debug)]
pub struct ColumnInfo {
    pub cid: i64,
    pub name: String,
    pub decl_type: String,
    pub notnull: bool,
    pub default: Option<String>,
    /// 0 = not part of the primary key, otherwise 1-based position in it.
    pub pk: i64,
    /// 0 normal, 1 hidden (virtual table), 2 generated virtual, 3 generated stored
    pub hidden: i64,
}

#[derive(Clone, Debug)]
pub struct IndexInfo {
    pub name: String,
    pub unique: bool,
    /// "c" = CREATE INDEX, "u" = UNIQUE constraint, "pk" = PRIMARY KEY
    pub origin: String,
    pub partial: bool,
    pub columns: Vec<String>,
}

#[derive(Clone, Debug)]
pub struct ForeignKey {
    pub table: String,
    pub from: String,
    pub to: String,
    pub on_update: String,
    pub on_delete: String,
}

#[derive(Clone, Debug, Default)]
pub struct TableDetails {
    pub columns: Vec<ColumnInfo>,
    pub indexes: Vec<IndexInfo>,
    pub foreign_keys: Vec<ForeignKey>,
    pub without_rowid: bool,
    pub strict: bool,
    pub is_view: bool,
}

impl TableDetails {
    /// Columns that identify a row for UPDATE/DELETE from the grid.
    pub fn has_rowid(&self) -> bool {
        !self.is_view && !self.without_rowid
    }
    pub fn pk_columns(&self) -> Vec<String> {
        let mut pk: Vec<&ColumnInfo> = self.columns.iter().filter(|c| c.pk > 0).collect();
        pk.sort_by_key(|c| c.pk);
        pk.into_iter().map(|c| c.name.clone()).collect()
    }
}

// ---------------------------------------------------------------------------
// Query results
// ---------------------------------------------------------------------------

#[derive(Clone, Debug, Default)]
pub struct QueryResult {
    pub columns: Vec<String>,
    pub rows: Vec<Vec<Value>>,
    pub truncated: bool,
}

#[derive(Clone, Debug)]
pub struct StatementOutcome {
    pub sql: String,
    pub ok: bool,
    pub message: String,
    #[allow(dead_code)]
    pub millis: f64,
    pub result: Option<QueryResult>,
}

// ---------------------------------------------------------------------------
// Database
// ---------------------------------------------------------------------------

pub struct Database {
    pub conn: Connection,
    pub path: PathBuf,
    pub read_only: bool,
    pub log: Vec<LogEntry>,
    savepoint_active: bool,
}

impl Database {
    pub fn open(path: &Path, read_only: bool) -> Result<Self> {
        let flags = if read_only {
            OpenFlags::SQLITE_OPEN_READ_ONLY | OpenFlags::SQLITE_OPEN_URI
        } else {
            OpenFlags::SQLITE_OPEN_READ_WRITE
                | OpenFlags::SQLITE_OPEN_CREATE
                | OpenFlags::SQLITE_OPEN_URI
        };
        let conn = Connection::open_with_flags(path, flags).map_err(|e| e.to_string())?;
        let mut db = Database {
            conn,
            path: path.to_path_buf(),
            read_only,
            log: Vec::new(),
            savepoint_active: false,
        };
        // Touch the schema so a bad/non-SQLite file errors out immediately.
        db.query(LogSource::App, "SELECT COUNT(*) FROM sqlite_schema;", &[])?;
        Ok(db)
    }

    #[allow(dead_code)]
    pub fn open_in_memory() -> Result<Self> {
        let conn = Connection::open_in_memory().map_err(|e| e.to_string())?;
        Ok(Database {
            conn,
            path: PathBuf::from(":memory:"),
            read_only: false,
            log: Vec::new(),
            savepoint_active: false,
        })
    }

    pub fn file_name(&self) -> String {
        self.path
            .file_name()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_else(|| self.path.display().to_string())
    }

    // ----- logging ---------------------------------------------------------

    pub fn push_log(&mut self, source: LogSource, sql: &str, ok: bool, millis: f64, detail: String) {
        self.log.push(LogEntry {
            time: chrono::Local::now().format("%H:%M:%S%.3f").to_string(),
            source,
            sql: sql.trim().to_string(),
            ok,
            millis,
            detail,
        });
        const MAX_LOG: usize = 5000;
        if self.log.len() > MAX_LOG {
            let excess = self.log.len() - MAX_LOG;
            self.log.drain(0..excess);
        }
    }

    // ----- pending-changes (savepoint) handling ------------------------------

    /// True when there are uncommitted changes (our savepoint, or a
    /// transaction the user opened manually with BEGIN).
    pub fn has_pending_changes(&self) -> bool {
        !self.conn.is_autocommit()
    }

    /// Start the restore point that groups UI edits, if not already active.
    pub fn ensure_savepoint(&mut self) -> Result<()> {
        if self.conn.is_autocommit() {
            self.savepoint_active = false;
        }
        if !self.savepoint_active {
            self.execute(LogSource::App, &format!("SAVEPOINT \"{SAVEPOINT}\";"), &[])?;
            self.savepoint_active = true;
        }
        Ok(())
    }

    /// "Write Changes": release our savepoint and commit any open transaction.
    pub fn write_changes(&mut self) -> Result<()> {
        if self.savepoint_active && !self.conn.is_autocommit() {
            self.execute(LogSource::App, &format!("RELEASE \"{SAVEPOINT}\";"), &[])?;
        }
        self.savepoint_active = false;
        if !self.conn.is_autocommit() {
            self.execute(LogSource::App, "COMMIT;", &[])?;
        }
        Ok(())
    }

    /// "Revert Changes": roll back everything since the last write.
    pub fn revert_changes(&mut self) -> Result<()> {
        self.savepoint_active = false;
        if !self.conn.is_autocommit() {
            self.execute(LogSource::App, "ROLLBACK;", &[])?;
        }
        Ok(())
    }

    // ----- execution primitives ----------------------------------------------

    /// Prepare, bind, run a statement that may or may not return rows.
    /// The log records the fully expanded SQL (parameters inlined), so the
    /// user sees exactly what ran.
    fn run(
        &mut self,
        source: LogSource,
        sql: &str,
        params: &[Value],
        row_limit: usize,
    ) -> Result<(Option<QueryResult>, usize, String)> {
        let start = Instant::now();
        let outcome = (|| -> rusqlite::Result<(Option<QueryResult>, usize, String)> {
            let mut stmt = self.conn.prepare(sql)?;
            for (i, p) in params.iter().enumerate() {
                stmt.raw_bind_parameter(i + 1, p)?;
            }
            let expanded = stmt.expanded_sql().unwrap_or_else(|| sql.to_string());
            if stmt.column_count() > 0 {
                let columns: Vec<String> =
                    stmt.column_names().iter().map(|s| s.to_string()).collect();
                let n = columns.len();
                let mut rows = Vec::new();
                let mut truncated = false;
                let mut it = stmt.raw_query();
                while let Some(row) = it.next()? {
                    if rows.len() >= row_limit {
                        truncated = true;
                        break;
                    }
                    let mut r = Vec::with_capacity(n);
                    for i in 0..n {
                        r.push(row.get::<_, Value>(i)?);
                    }
                    rows.push(r);
                }
                let count = rows.len();
                Ok((Some(QueryResult { columns, rows, truncated }), count, expanded))
            } else {
                // sqlite3_changes() keeps its old value after non-DML
                // statements, so only trust it when total_changes moved.
                let before = self.conn.total_changes();
                let changed = stmt.raw_execute()?;
                let changed = if self.conn.total_changes() == before { 0 } else { changed };
                Ok((None, changed, expanded))
            }
        })();
        let millis = start.elapsed().as_secs_f64() * 1000.0;
        match outcome {
            Ok((res, n, expanded)) => {
                let detail = match &res {
                    Some(r) => format!("{} row(s) returned{}", n, if r.truncated { " (truncated)" } else { "" }),
                    None => format!("{n} row(s) affected"),
                };
                self.push_log(source, &expanded, true, millis, detail);
                if self.conn.is_autocommit() {
                    self.savepoint_active = false;
                }
                Ok((res, n, expanded))
            }
            Err(e) => {
                let msg = e.to_string();
                self.push_log(source, sql, false, millis, msg.clone());
                Err(msg)
            }
        }
    }

    pub fn query(&mut self, source: LogSource, sql: &str, params: &[Value]) -> Result<QueryResult> {
        self.query_limited(source, sql, params, usize::MAX)
    }

    pub fn query_limited(
        &mut self,
        source: LogSource,
        sql: &str,
        params: &[Value],
        limit: usize,
    ) -> Result<QueryResult> {
        let (res, _, _) = self.run(source, sql, params, limit)?;
        Ok(res.unwrap_or_default())
    }

    pub fn execute(&mut self, source: LogSource, sql: &str, params: &[Value]) -> Result<usize> {
        let (_, n, _) = self.run(source, sql, params, usize::MAX)?;
        Ok(n)
    }

    /// Run an app-generated *modifying* statement inside the restore point.
    pub fn execute_edit(&mut self, sql: &str, params: &[Value]) -> Result<usize> {
        if self.read_only {
            return Err("Database is opened read-only.".into());
        }
        self.ensure_savepoint()?;
        self.execute(LogSource::App, sql, params)
    }

    /// Scalar helper for internal lookups.
    pub fn scalar(&mut self, sql: &str) -> Result<Value> {
        let r = self.query(LogSource::App, sql, &[])?;
        Ok(r.rows.into_iter().next().and_then(|r| r.into_iter().next()).unwrap_or(Value::Null))
    }

    // ----- Execute SQL tab -----------------------------------------------------

    /// Execute a user script statement by statement, as DB4S does.
    /// Modifying statements run inside the restore point so they can be
    /// reverted; statements that cannot run inside a transaction (VACUUM,
    /// PRAGMA journal_mode, BEGIN/COMMIT...) require no pending changes.
    pub fn execute_script(&mut self, script: &str, row_limit: usize) -> Vec<StatementOutcome> {
        let mut out = Vec::new();
        for sql in split_statements(script) {
            let start = Instant::now();
            let kind = classify(&sql);
            let mut pre_error: Option<String> = None;

            match kind {
                StmtClass::NeedsNoTransaction => {
                    if self.has_pending_changes() {
                        pre_error = Some(
                            "This statement cannot run inside a transaction. \
                             Write or revert pending changes first."
                                .into(),
                        );
                    }
                }
                StmtClass::TransactionControl => {
                    // The user is taking over transaction handling: fold our
                    // restore point into whatever they are doing.
                    if self.savepoint_active && self.has_pending_changes() {
                        pre_error = Some(
                            "Pending changes are held in a restore point. \
                             Write or revert them before managing transactions manually."
                                .into(),
                        );
                    }
                }
                StmtClass::Normal => {
                    let readonly = self
                        .conn
                        .prepare(&sql)
                        .map(|s| s.readonly())
                        .unwrap_or(true);
                    if !readonly {
                        if self.read_only {
                            pre_error = Some("Database is opened read-only.".into());
                        } else if let Err(e) = self.ensure_savepoint() {
                            pre_error = Some(e);
                        }
                    }
                }
            }

            if let Some(err) = pre_error {
                self.push_log(LogSource::User, &sql, false, 0.0, err.clone());
                out.push(StatementOutcome { sql, ok: false, message: err, millis: 0.0, result: None });
                break;
            }

            match self.run(LogSource::User, &sql, &[], row_limit) {
                Ok((res, n, _)) => {
                    let millis = start.elapsed().as_secs_f64() * 1000.0;
                    let message = match &res {
                        Some(r) => format!(
                            "{} row(s) returned in {:.0} ms{}",
                            n,
                            millis,
                            if r.truncated { format!(" (display limited to {row_limit})") } else { String::new() }
                        ),
                        None => format!("Execution finished without errors. {n} row(s) affected in {millis:.0} ms"),
                    };
                    out.push(StatementOutcome { sql, ok: true, message, millis, result: res });
                }
                Err(e) => {
                    let millis = start.elapsed().as_secs_f64() * 1000.0;
                    out.push(StatementOutcome { sql, ok: false, message: e, millis, result: None });
                    break; // stop at first error, like DB4S
                }
            }
        }
        out
    }

    // ----- schema introspection -----------------------------------------------

    pub fn schema_objects(&mut self) -> Result<Vec<SchemaObject>> {
        let r = self.query(
            LogSource::App,
            "SELECT type, name, tbl_name, sql FROM sqlite_schema ORDER BY type, name;",
            &[],
        )?;
        let mut objs = Vec::new();
        for row in r.rows {
            let kind = match as_text(&row[0]).as_str() {
                "table" => ObjKind::Table,
                "view" => ObjKind::View,
                "index" => ObjKind::Index,
                "trigger" => ObjKind::Trigger,
                _ => continue,
            };
            let sql = match &row[3] {
                Value::Null => None,
                v => Some(as_text(v)),
            };
            objs.push(SchemaObject { kind, name: as_text(&row[1]), tbl_name: as_text(&row[2]), sql });
        }
        Ok(objs)
    }

    #[allow(dead_code)]
    pub fn table_names(&mut self, include_views: bool) -> Result<Vec<String>> {
        Ok(self
            .schema_objects()?
            .into_iter()
            .filter(|o| o.kind == ObjKind::Table || (include_views && o.kind == ObjKind::View))
            .map(|o| o.name)
            .collect())
    }

    pub fn table_details(&mut self, table: &str) -> Result<TableDetails> {
        let q = quote_ident(table);
        let mut d = TableDetails::default();

        let cols = self.query(LogSource::App, &format!("PRAGMA table_xinfo({q});"), &[])?;
        for row in cols.rows {
            d.columns.push(ColumnInfo {
                cid: as_int(&row[0]),
                name: as_text(&row[1]),
                decl_type: as_text(&row[2]),
                notnull: as_int(&row[3]) != 0,
                default: match &row[4] {
                    Value::Null => None,
                    v => Some(as_text(v)),
                },
                pk: as_int(&row[5]),
                hidden: row.get(6).map(as_int).unwrap_or(0),
            });
        }

        // table_list gives us WITHOUT ROWID / STRICT flags (SQLite >= 3.37).
        if let Ok(tl) = self.query(
            LogSource::App,
            "SELECT type, wr, strict FROM pragma_table_list WHERE schema = 'main' AND name = ?1;",
            &[Value::Text(table.to_string())],
        ) {
            if let Some(row) = tl.rows.first() {
                d.is_view = as_text(&row[0]) == "view";
                d.without_rowid = as_int(&row[1]) != 0;
                d.strict = as_int(&row[2]) != 0;
            }
        }

        let idx = self.query(LogSource::App, &format!("PRAGMA index_list({q});"), &[])?;
        for row in idx.rows {
            let name = as_text(&row[1]);
            let cols = self
                .query(LogSource::App, &format!("PRAGMA index_xinfo({});", quote_ident(&name)), &[])
                .map(|r| {
                    r.rows
                        .iter()
                        .filter(|c| as_int(&c[5]) == 1) // key columns only
                        .map(|c| {
                            let n = match &c[2] {
                                Value::Null => "<expr>".to_string(),
                                v => as_text(v),
                            };
                            if as_int(&c[3]) == 1 { format!("{n} DESC") } else { n }
                        })
                        .collect()
                })
                .unwrap_or_default();
            d.indexes.push(IndexInfo {
                name,
                unique: as_int(&row[2]) != 0,
                origin: as_text(&row[3]),
                partial: as_int(&row[4]) != 0,
                columns: cols,
            });
        }

        let fks = self.query(LogSource::App, &format!("PRAGMA foreign_key_list({q});"), &[])?;
        for row in fks.rows {
            d.foreign_keys.push(ForeignKey {
                table: as_text(&row[2]),
                from: as_text(&row[3]),
                to: as_text(&row[4]),
                on_update: as_text(&row[5]),
                on_delete: as_text(&row[6]),
            });
        }
        Ok(d)
    }

    pub fn row_count(&mut self, table: &str, where_sql: &str, params: &[Value]) -> Result<i64> {
        let r = self.query(
            LogSource::App,
            &format!("SELECT COUNT(*) FROM {}{};", quote_ident(table), where_sql),
            params,
        )?;
        Ok(r.rows.first().map(|r| as_int(&r[0])).unwrap_or(0))
    }

    // ----- pragmas / WAL -------------------------------------------------------

    pub fn get_pragma(&mut self, name: &str) -> Result<Value> {
        self.scalar(&format!("PRAGMA {name};"))
    }

    pub fn set_pragma(&mut self, name: &str, value: &str) -> Result<Value> {
        if self.read_only && !matches!(name, "cache_size" | "busy_timeout" | "query_only" | "temp_store") {
            return Err("Database is opened read-only.".into());
        }
        // journal_mode, page_size etc. can't change inside a transaction.
        if self.has_pending_changes() && pragma_needs_no_txn(name) {
            return Err(format!(
                "PRAGMA {name} cannot be changed while there are pending changes. Write or revert them first."
            ));
        }
        let r = self.query(LogSource::App, &format!("PRAGMA {name} = {value};"), &[])?;
        Ok(r.rows.into_iter().next().and_then(|r| r.into_iter().next()).unwrap_or(Value::Null))
    }

    /// PRAGMA wal_checkpoint(MODE) -> (busy, wal_frames, checkpointed_frames)
    pub fn wal_checkpoint(&mut self, mode: &str) -> Result<(i64, i64, i64)> {
        let r = self.query(LogSource::App, &format!("PRAGMA wal_checkpoint({mode});"), &[])?;
        let row = r.rows.first().ok_or("no result")?;
        Ok((as_int(&row[0]), as_int(&row[1]), as_int(&row[2])))
    }

    pub fn wal_files(&self) -> Vec<(String, Option<u64>)> {
        ["-wal", "-shm"]
            .iter()
            .map(|suf| {
                let p = PathBuf::from(format!("{}{}", self.path.display(), suf));
                let size = std::fs::metadata(&p).ok().map(|m| m.len());
                (p.file_name().map(|s| s.to_string_lossy().to_string()).unwrap_or_default(), size)
            })
            .collect()
    }

    // ----- SQL dump --------------------------------------------------------------

    /// Export the whole database as an SQL script (schema + INSERTs).
    pub fn dump_sql(&mut self, w: &mut impl std::io::Write) -> Result<usize> {
        let objs = self.schema_objects()?;
        let mut rows_written = 0usize;
        let io = |e: std::io::Error| e.to_string();
        writeln!(w, "BEGIN TRANSACTION;").map_err(io)?;
        for o in objs.iter().filter(|o| o.kind == ObjKind::Table) {
            if o.name.starts_with("sqlite_") {
                continue;
            }
            if let Some(sql) = &o.sql {
                writeln!(w, "{};", sql.trim_end_matches(';')).map_err(io)?;
            }
            let r = self.query(LogSource::App, &format!("SELECT * FROM {};", quote_ident(&o.name)), &[])?;
            let cols = r.columns.iter().map(|c| quote_ident(c)).collect::<Vec<_>>().join(",");
            for row in &r.rows {
                let vals = row.iter().map(sql_literal).collect::<Vec<_>>().join(",");
                writeln!(w, "INSERT INTO {} ({}) VALUES ({});", quote_ident(&o.name), cols, vals).map_err(io)?;
                rows_written += 1;
            }
        }
        for kind in [ObjKind::Index, ObjKind::View, ObjKind::Trigger] {
            for o in objs.iter().filter(|o| o.kind == kind) {
                if let Some(sql) = &o.sql {
                    writeln!(w, "{};", sql.trim_end_matches(';')).map_err(io)?;
                }
            }
        }
        writeln!(w, "COMMIT;").map_err(io)?;
        Ok(rows_written)
    }
}

/// PRAGMAs that SQLite refuses (or silently ignores) inside a transaction.
pub fn pragma_needs_no_txn(name: &str) -> bool {
    matches!(name, "journal_mode" | "page_size" | "auto_vacuum" | "foreign_keys" | "locking_mode" | "encoding")
}

// ---------------------------------------------------------------------------
// Statement splitting / classification
// ---------------------------------------------------------------------------

/// Split a script into complete statements using SQLite's own
/// `sqlite3_complete()`, so semicolons inside strings, comments and
/// `CREATE TRIGGER ... BEGIN ... END` bodies are handled correctly.
pub fn split_statements(script: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut start = 0usize;
    for (i, ch) in script.char_indices() {
        if ch != ';' {
            continue;
        }
        let candidate = &script[start..=i];
        if is_complete(candidate) {
            let s = candidate.trim();
            if !strip_comments(s).trim().trim_matches(';').trim().is_empty() {
                out.push(s.to_string());
            }
            start = i + 1;
        }
    }
    let rest = script[start..].trim();
    if !strip_comments(rest).trim().is_empty() {
        out.push(rest.to_string());
    }
    out
}

fn is_complete(sql: &str) -> bool {
    match std::ffi::CString::new(sql) {
        Ok(c) => unsafe { rusqlite::ffi::sqlite3_complete(c.as_ptr()) != 0 },
        Err(_) => false,
    }
}

/// Remove `-- line` and `/* block */` comments (outside of quotes).
pub fn strip_comments(sql: &str) -> String {
    let b = sql.as_bytes();
    let mut out = String::with_capacity(sql.len());
    let mut i = 0;
    let mut quote: Option<u8> = None;
    while i < b.len() {
        let c = b[i];
        if let Some(q) = quote {
            out.push(c as char);
            if c == q {
                quote = None;
            }
            i += 1;
            continue;
        }
        if c == b'\'' || c == b'"' || c == b'`' || c == b'[' {
            quote = Some(if c == b'[' { b']' } else { c });
            out.push(c as char);
            i += 1;
        } else if c == b'-' && b.get(i + 1) == Some(&b'-') {
            while i < b.len() && b[i] != b'\n' {
                i += 1;
            }
        } else if c == b'/' && b.get(i + 1) == Some(&b'*') {
            i += 2;
            while i + 1 < b.len() && !(b[i] == b'*' && b[i + 1] == b'/') {
                i += 1;
            }
            i += 2;
            out.push(' ');
        } else {
            // copy full UTF-8 char
            let ch = sql[i..].chars().next().unwrap();
            out.push(ch);
            i += ch.len_utf8();
        }
    }
    out
}

#[derive(Debug, PartialEq, Eq)]
pub enum StmtClass {
    Normal,
    TransactionControl,
    NeedsNoTransaction,
}

pub fn classify(sql: &str) -> StmtClass {
    let s = strip_comments(sql).trim().to_ascii_uppercase();
    let words: Vec<&str> = s.split(|c: char| c.is_whitespace() || c == ';' || c == '(' || c == '=').filter(|w| !w.is_empty()).collect();
    match words.as_slice() {
        ["BEGIN", ..] | ["COMMIT", ..] | ["END", ..] => StmtClass::TransactionControl,
        ["ROLLBACK", "TO", ..] | ["ROLLBACK", "TRANSACTION", "TO", ..] => StmtClass::Normal,
        ["ROLLBACK", ..] => StmtClass::TransactionControl,
        ["VACUUM", ..] | ["ATTACH", ..] | ["DETACH", ..] => StmtClass::NeedsNoTransaction,
        ["PRAGMA", name, rest @ ..] if !rest.is_empty() => {
            let n = name.rsplit('.').next().unwrap_or(name).to_ascii_lowercase();
            if pragma_needs_no_txn(&n) {
                StmtClass::NeedsNoTransaction
            } else {
                StmtClass::Normal
            }
        }
        _ => StmtClass::Normal,
    }
}

// ---------------------------------------------------------------------------
// Value helpers
// ---------------------------------------------------------------------------

pub fn quote_ident(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

pub fn sql_literal(v: &Value) -> String {
    match v {
        Value::Null => "NULL".into(),
        Value::Integer(i) => i.to_string(),
        Value::Real(f) => {
            if f.is_finite() {
                let s = format!("{f:?}");
                s
            } else if f.is_nan() {
                "NULL".into()
            } else if *f > 0.0 {
                "9e999".into()
            } else {
                "-9e999".into()
            }
        }
        Value::Text(t) => format!("'{}'", t.replace('\'', "''")),
        Value::Blob(b) => format!("X'{}'", hex(b)),
    }
}

pub fn hex(b: &[u8]) -> String {
    let mut s = String::with_capacity(b.len() * 2);
    for byte in b {
        s.push_str(&format!("{byte:02X}"));
    }
    s
}

pub fn as_text(v: &Value) -> String {
    match v {
        Value::Null => String::new(),
        Value::Integer(i) => i.to_string(),
        Value::Real(f) => format_real(*f),
        Value::Text(t) => t.clone(),
        Value::Blob(b) => String::from_utf8_lossy(b).to_string(),
    }
}

pub fn as_int(v: &Value) -> i64 {
    match v {
        Value::Integer(i) => *i,
        Value::Real(f) => *f as i64,
        Value::Text(t) => t.trim().parse().unwrap_or(0),
        _ => 0,
    }
}

/// Shortest round-trippable representation (no lost precision on export).
pub fn format_real(f: f64) -> String {
    if f.is_finite() && f == f.trunc() && f.abs() < 1e15 {
        format!("{f:.1}")
    } else {
        format!("{f}")
    }
}

/// Text shown in a grid cell.
pub fn display_value(v: &Value) -> String {
    match v {
        Value::Null => "NULL".into(),
        Value::Blob(b) => format!("BLOB ({} bytes)", b.len()),
        Value::Text(t) => {
            let first = t.lines().next().unwrap_or("");
            let mut s: String = first.chars().take(200).collect();
            if s.len() < t.len() {
                s.push('…');
            }
            s
        }
        other => as_text(other),
    }
}

pub fn type_name(v: &Value) -> &'static str {
    match v {
        Value::Null => "NULL",
        Value::Integer(_) => "INTEGER",
        Value::Real(_) => "REAL",
        Value::Text(_) => "TEXT",
        Value::Blob(_) => "BLOB",
    }
}

